"""ERD HTML(팀 공유 ERD 최종본)에서 PostgreSQL DDL을 만든다.

입력: ERD HTML 안의 `const D=` JSON(표·열·기본값·PK·UNIQUE·CHECK·FK). 팀원 DB(PostgreSQL 17 + pgvector)의 카탈로그를 뽑은 값이다.
출력: db/01_erd_schema.sql — 앱이 쓰는 public·regulations 스키마만 만든다. growpath_legacy·growpath_meta(과거 기록·적용 이력)는 넣지 않는다.
순서: 확장·스키마·시퀀스 → 표(열·PK·UNIQUE·CHECK) → FK(ALTER TABLE). FK를 마지막에 붙여 표 순서를 신경 쓰지 않게 했다.
FK 대상은 정의 문장의 표 이름 대신 JSON의 target(스키마 포함)으로 적는다(검색 경로에 따라 스키마가 빠질 수 있어서).

실행: python tools/gen_schema.py data/seed/ERD_최종_20261021.html db/01_erd_schema.sql
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

KEEP_SCHEMAS = ('public', 'regulations')


def load_erd(path: Path) -> dict:
    text = path.read_text(encoding='utf-8')
    start = text.index('const D=') + len('const D=')
    obj, _ = json.JSONDecoder().raw_decode(text[start:])
    return obj


def qname(full: str) -> str:
    schema, table = full.split('.', 1)
    return f'{schema}.{table}'


def column_sql(col: dict) -> str:
    parts = [f'"{col["column"]}"' if not re.fullmatch(r'[a-z_][a-z0-9_]*', col['column']) else col['column'], col['type']]
    if col.get('generated') == 's':
        parts.append(f'GENERATED ALWAYS AS ({col["default"]}) STORED')
    elif col.get('identity') == 'd':
        parts.append('GENERATED BY DEFAULT AS IDENTITY')
    elif col.get('identity') == 'a':
        parts.append('GENERATED ALWAYS AS IDENTITY')
    elif col.get('default') is not None:
        parts.append(f'DEFAULT {col["default"]}')
    if col.get('not_null'):
        parts.append('NOT NULL')
    return ' '.join(parts)


def fk_tail(definition: str) -> str:
    """정의 문장 끝의 ON DELETE / ON UPDATE / DEFERRABLE 같은 꼬리말만 남긴다"""
    m = re.search(r'\)\s*((?:ON (?:DELETE|UPDATE)|MATCH|DEFERRABLE|NOT DEFERRABLE|INITIALLY).*)$', definition)
    return (' ' + m.group(1).strip()) if m else ''


def build(erd: dict) -> str:
    tables = {k: v for k, v in erd.items() if k.split('.')[0] in KEEP_SCHEMAS}
    out = [
        '-- GrowPath 5차 목업 · 팀 ERD 최종본(2026-10-21 받은 파일)에서 만든 표 정의. 손으로 고치지 말고 tools/gen_schema.py 로 다시 만든다.',
        '-- public·regulations 스키마만 만든다(growpath_legacy·growpath_meta 제외). 앱 전용 보조 표는 02_app_ext.sql.',
        'CREATE EXTENSION IF NOT EXISTS vector;',
        'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
    ]
    for s in KEEP_SCHEMAS:
        if s != 'public':
            out.append(f'CREATE SCHEMA IF NOT EXISTS {s};')
    # 기본값에 쓰인 시퀀스 (예: nextval('users_user_id_seq'::regclass)) — 표 스키마와 같은 곳에 만든다
    seqs = set()
    for name, t in tables.items():
        for c in t['columns']:
            m = re.search(r"nextval\('([^']+)'", c.get('default') or '')
            if m:
                seq = m.group(1)
                seqs.add(seq if '.' in seq else f'{name.split(".")[0]}.{seq}')
    for seq in sorted(seqs):
        out.append(f'CREATE SEQUENCE IF NOT EXISTS {seq};')
    out.append('')
    fks = []
    for name in sorted(tables):
        t = tables[name]
        lines = [column_sql(c) for c in t['columns']]
        for con in t.get('constraints', []):
            if con['type'] in ('p', 'u', 'c'):
                lines.append(f'CONSTRAINT {con["name"]} {con["definition"]}')
        label = (t.get('label') or '').replace('*/', '')
        out.append(f'-- {label} (팀원 DB 행 수 {t.get("rows", "?")})')
        out.append(f'CREATE TABLE IF NOT EXISTS {qname(name)} (\n  ' + ',\n  '.join(lines) + '\n);')
        for fk in t.get('fks', []):
            if fk['target'].split('.')[0] not in KEEP_SCHEMAS:
                out.append(f'-- FK {fk["name"]} 는 만들지 않음: 대상 {fk["target"]} 가 이 DB에 없음')
                continue
            cols = ', '.join(fk['columns'])
            tcols = ', '.join(fk['target_columns'])
            fks.append(f'ALTER TABLE {qname(name)} ADD CONSTRAINT {fk["name"]} FOREIGN KEY ({cols}) '
                       f'REFERENCES {qname(fk["target"])}({tcols}){fk_tail(fk["definition"])};')
        out.append('')
    out.append('-- 외래키')
    out.extend(fks)
    # 시퀀스를 열의 소유로 묶는다(표를 지우면 함께 지워지게)
    for name, t in tables.items():
        for c in t['columns']:
            m = re.search(r"nextval\('([^']+)'", c.get('default') or '')
            if m:
                seq = m.group(1) if '.' in m.group(1) else f'{name.split(".")[0]}.{m.group(1)}'
                out.append(f'ALTER SEQUENCE {seq} OWNED BY {qname(name)}.{c["column"]};')
    return '\n'.join(out) + '\n'


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit('사용법: python tools/gen_schema.py <ERD html> <출력 sql>')
    erd = load_erd(Path(sys.argv[1]))
    Path(sys.argv[2]).write_text(build(erd), encoding='utf-8')
    kept = [k for k in erd if k.split('.')[0] in KEEP_SCHEMAS]
    print(f'표 {len(kept)}개 → {sys.argv[2]}')


if __name__ == '__main__':
    main()
